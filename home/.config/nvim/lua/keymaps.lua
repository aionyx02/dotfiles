-- =====================================================================
--  自訂鍵位 — 全部集中在這個檔案
--
--  ★ 原則：vim 的原生鍵一個都不覆蓋。這裡只有「原生根本沒有這個功能」的
--    東西 —— vim 從來沒有「模糊搜尋檔案」這個鍵。
--
--  ★ 全部掛在 leader 底下。leader 目前是反斜線 \ (vim 原生預設，規範中
--    明確保留給使用者的前綴鍵)。所以下面的 \f 意思是「先按 \ 再按 f」。
--
--  ★ gitsigns 的 ]c / [c 不在這裡，在 lua/plugins/gitsigns.lua ——
--    那兩個是只在有 git 的 buffer 裡才生效的鍵，綁在外掛的 on_attach 裡
--    才不會在非 git 檔案上留下死鍵。
-- =====================================================================

local map = vim.keymap.set

-- --- fzf-lua ---------------------------------------------------------
map('n', '<leader>f', '<cmd>FzfLua files<cr>', { desc = '找檔案(模糊搜尋檔名)' })
map('n', '<leader>g', '<cmd>FzfLua live_grep<cr>', { desc = '全文搜尋(ripgrep)' })
map('n', '<leader>b', '<cmd>FzfLua buffers<cr>', { desc = '切換已開啟的檔案' })

-- --- yazi ------------------------------------------------------------
-- \y 開在當前檔案的位置(游標會停在這個檔案上)，\Y 開在當前工作目錄。
map('n', '<leader>y', '<cmd>Yazi<cr>', { desc = 'yazi：開在當前檔案的位置' })
map('n', '<leader>Y', '<cmd>Yazi cwd<cr>', { desc = 'yazi：開在當前工作目錄' })
